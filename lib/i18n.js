	const STRINGS = {en, de};

	let locale = 'en';

	function humanize(key) {
		const last = String(key).split('.').pop();
		return last.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/^./, c => c.toUpperCase());
	}

	function t(key, vars) {
		const table = STRINGS[locale] || en;
		let str = table[key];
		if (str === undefined) str = en[key];
		if (str === undefined) str = humanize(key);
		if (vars) str = str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
		return str;
	}

	function resolveLocale(pref) {
		if (pref && pref !== 'auto' && STRINGS[pref]) return pref;
		let nav = 'en';
		try {
			nav = (root.navigator && (root.navigator.language || '')).slice(0, 2).toLowerCase() || 'en';
		} catch (e) {
			/* worker without navigator.language */
		}
		return STRINGS[nav] ? nav : 'en';
	}

	BLP.i18n = {
		STRINGS,
		t,
		has: key => en[key] !== undefined,
		setLocale(pref) {
			locale = resolveLocale(pref);
			return locale;
		},
		getLocale: () => locale,
		/** Export the merged table for the active locale (used to hand strings to the page context). */
		table() {
			return Object.assign({}, en, STRINGS[locale] || {});
		},
		/** Replace [data-i18n], [data-i18n-title] and [data-i18n-placeholder] attributes in a DOM tree. */
		localizeDom(rootEl) {
			rootEl.querySelectorAll('[data-i18n]').forEach(el => (el.textContent = t(el.dataset.i18n)));
			rootEl.querySelectorAll('[data-i18n-title]').forEach(el => (el.title = t(el.dataset.i18nTitle)));
			rootEl.querySelectorAll('[data-i18n-placeholder]').forEach(el => (el.placeholder = t(el.dataset.i18nPlaceholder)));
		},
	};
	BLP.t = t;
